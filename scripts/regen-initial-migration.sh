#!/usr/bin/env bash
# Pre-G1 only: rebuild the single initial migration from the models (drops the dev schema).
# After G1, schema changes are new revisions: `make revision MSG="…"`.
set -euo pipefail
cd "$(dirname "$0")/.."
uv run alembic -c db/alembic.ini downgrade base
rm -f db/alembic/versions/*_domain_model_v1.py
uv run alembic -c db/alembic.ini revision --autogenerate -m "domain model v1" >/dev/null
f=$(ls db/alembic/versions/*_domain_model_v1.py)
python3 - "$f" <<'PY'
import sys
from pathlib import Path
p = Path(sys.argv[1])
t = p.read_text()
old = "def upgrade() -> None:\n    # ### commands auto generated by Alembic - please adjust! ###\n"
new = ("def upgrade() -> None:\n"
       "    # Extensions first; on Docker they already exist (db/init/00_extensions.sql).\n"
       '    op.execute("CREATE EXTENSION IF NOT EXISTS postgis")\n'
       '    op.execute("CREATE EXTENSION IF NOT EXISTS vector")\n'
       "    # ### commands auto generated by Alembic - please adjust! ###\n")
assert old in t
p.write_text(t.replace(old, new, 1))
PY
uv run alembic -c db/alembic.ini upgrade head
uv run alembic -c db/alembic.ini check
